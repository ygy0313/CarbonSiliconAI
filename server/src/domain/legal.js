// 纯文本渲染：小程序与需要整段复制的地方共用，保证与结构化数据同源。
function toPlain(doc) {
  if (!doc) return ''
  const out = [`${doc.title}（版本 ${doc.version}，${doc.effectiveAt} 生效）`, '']
  for (const s of doc.sections) {
    out.push(s.title)
    for (const p of s.paragraphs || []) out.push(p)
    for (const it of s.items || []) out.push(`· ${it}`)
    for (const p of s.paragraphs_after || []) out.push(p)
    out.push('')
  }
  return out.join('\n').trim()
}

